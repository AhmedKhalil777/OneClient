export const DEFAULT_COLOR_THEME = "oneclient-dark";
/**
 * The icon theme used when the user hasn't chosen one (or their choice is gone): the Material Icon Theme that ships in
 * the built-in Miscellaneous plugin. There is no separate built-in theme — if no icon theme is installed at all, the
 * explorer simply shows each node's own `$(icon)`.
 */
export const DEFAULT_ICON_THEME = "oneclient-material-icons";

/** Base palette a theme of `kind` inherits unset keys from. */
export function baseColorsFor(kind: ThemeKind): Record<string, string> {
  return (BUILTIN_COLOR_THEMES.find((t) => t.kind === kind) ?? BUILTIN_COLOR_THEMES[0]!).colors;
}
