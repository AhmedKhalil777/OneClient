/**
 * Turns the `material-icon-theme` npm package (https://github.com/material-extensions/vscode-material-icon-theme,
 * MIT) into a oneClient icon theme:
 *
 *   dist/icon-theme.json   file/folder mappings in oneClient's IconThemeFile format
 *   dist/icons/*.svg       the icons it references
 *   dist/LICENSE-material-icon-theme.txt
 *
 * `dist/` is generated (git-ignored): run `pnpm --filter oneclient-material-icons run build`
 * (the root `pnpm build` does it).
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const pkgDir = dirname(require.resolve("material-icon-theme/package.json", { paths: [root] }).replace(/\\/g, "/"));
const manifest = JSON.parse(readFileSync(join(pkgDir, "dist", "material-icons.json"), "utf8"));
const out = join(root, "dist");

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "icons"), { recursive: true });

// Icon ids: oneClient ids are lower-case/dash-separated; Material's use underscores ("react_ts", "toml_light").
const idOf = (name) => `mi-${name.toLowerCase().replace(/_/g, "-")}`;

const icons = {};
const seenIds = new Map();
for (const [name, def] of Object.entries(manifest.iconDefinitions)) {
  const id = idOf(name);
  if (seenIds.has(id)) throw new Error(`icon id collision: "${name}" and "${seenIds.get(id)}" → ${id}`);
  seenIds.set(id, name);
  const file = basename(def.iconPath);
  const src = join(pkgDir, "icons", file);
  if (!existsSync(src)) throw new Error(`missing icon file for "${name}": ${src}`);
  copyFileSync(src, join(out, "icons", file));
  icons[id] = `icons/${file}`;
}

// Folder names: Material lists every spelling (".src", "_src", "-src", "__src__"). oneClient looks names up
// with those characters stripped (see normalizeFolderName), so only the canonical spelling is stored.
const canonicalFolder = (k) => k.toLowerCase().replace(/^[._-]+|[._-]+$/g, "") || k.toLowerCase();

const mappingTable = (source, normalize = (k) => k.toLowerCase()) => {
  const table = {};
  for (const [name, iconName] of Object.entries(source ?? {})) {
    const key = normalize(name);
    // First spelling wins; the canonical one is listed before its decorated variants.
    if (!(key in table)) table[key] = idOf(iconName);
  }
  return table;
};

const mappings = (m) => ({
  fileExtensions: mappingTable(m.fileExtensions),
  fileNames: mappingTable(m.fileNames),
  folderNames: mappingTable(m.folderNames, canonicalFolder),
  folderNamesExpanded: mappingTable(m.folderNamesExpanded, canonicalFolder),
});

const withoutEmpty = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => !(typeof v === "object" && Object.keys(v).length === 0)));

const theme = {
  $comment: "Generated by scripts/generate.mjs from material-icon-theme (MIT). Do not edit.",
  colored: true,
  icons,
  file: idOf(manifest.file),
  folder: idOf(manifest.folder),
  folderExpanded: idOf(manifest.folderExpanded),
  ...mappings(manifest),
  light: withoutEmpty(mappings(manifest.light ?? {})),
  hc: withoutEmpty(mappings(manifest.highContrast ?? {})),
};

writeFileSync(join(out, "icon-theme.json"), JSON.stringify(theme));
copyFileSync(join(pkgDir, "LICENSE"), join(out, "LICENSE-material-icon-theme.txt"));

const count = (o) => Object.keys(o).length;
console.log(
  `material icons: ${count(icons)} icons, ${count(theme.fileExtensions)} extensions, ${count(theme.fileNames)} file names, ` +
    `${count(theme.folderNames)} folder names → ${join("dist", "icon-theme.json")}`,
);
